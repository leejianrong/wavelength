// Writes src/theme/tokens.css: the Material 3 colour roles for light and dark from one seed colour,
// plus the type, shape, motion and state-layer tokens. Run with `npm run tokens`; the output is committed.
import { argbFromHex, hexFromArgb, Hct, MaterialDynamicColors, SchemeTonalSpot } from "@material/material-color-utilities";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

// A tuning-dial teal. The scheme's tertiary supplies the warm needle against it.
const SEED = "#0B7285";

const source = Hct.fromInt(argbFromHex(SEED));
const roles = new MaterialDynamicColors();
const dynamic = roles.allColors.filter((c) => c && typeof c.getArgb === "function" && !c.name.includes("palette_key"));
const block = (dark) => {
  const scheme = new SchemeTonalSpot(source, dark, 0);
  return dynamic.map((c) => `  --md-sys-color-${c.name.replaceAll("_", "-")}: ${hexFromArgb(c.getArgb(scheme))};`).join("\n");
};

const scale = {
  "display-large": ["brand", 3.5625, 4, 400, -0.015625],
  "display-medium": ["brand", 2.8125, 3.25, 400, 0],
  "display-small": ["brand", 2.25, 2.75, 400, 0],
  "headline-large": ["brand", 2, 2.5, 400, 0],
  "headline-medium": ["brand", 1.75, 2.25, 400, 0],
  "headline-small": ["brand", 1.5, 2, 400, 0],
  "title-large": ["brand", 1.375, 1.75, 400, 0],
  "title-medium": ["plain", 1, 1.5, 500, 0.009375],
  "title-small": ["plain", 0.875, 1.25, 500, 0.00625],
  "body-large": ["plain", 1, 1.5, 400, 0.03125],
  "body-medium": ["plain", 0.875, 1.25, 400, 0.015625],
  "body-small": ["plain", 0.75, 1, 400, 0.025],
  "label-large": ["plain", 0.875, 1.25, 500, 0.00625],
  "label-medium": ["plain", 0.75, 1, 500, 0.03125],
  "label-small": ["plain", 0.6875, 1, 500, 0.03125],
};
const type = Object.entries(scale)
  .map(
    ([role, [font, size, line, weight, tracking]]) =>
      `  --md-sys-typescale-${role}-font: var(--md-ref-typeface-${font});\n` +
      `  --md-sys-typescale-${role}-size: ${size}rem;\n` +
      `  --md-sys-typescale-${role}-line-height: ${line}rem;\n` +
      `  --md-sys-typescale-${role}-weight: ${weight};\n` +
      `  --md-sys-typescale-${role}-tracking: ${tracking}rem;`,
  )
  .join("\n");

const shape = { none: 0, "extra-small": 4, small: 8, medium: 12, large: 16, "extra-large": 28, full: 9999 };
const durations = { short1: 50, short2: 100, short3: 150, short4: 200, medium1: 250, medium2: 300, medium3: 350, medium4: 400, long1: 450, long2: 500 };

const css = `/* Generated by scripts/tokens.mjs from seed ${SEED}. Do not edit by hand; run \`npm run tokens\`. */
:root {
  color-scheme: light dark;
  --md-ref-typeface-brand: "Bricolage Grotesque Variable", system-ui, sans-serif;
  --md-ref-typeface-plain: "Figtree Variable", system-ui, sans-serif;
${block(false)}
${type}
${Object.entries(shape).map(([k, v]) => `  --md-sys-shape-corner-${k}: ${v}px;`).join("\n")}
${Object.entries(durations).map(([k, v]) => `  --md-sys-motion-duration-${k}: ${v}ms;`).join("\n")}
  --md-sys-motion-easing-standard: cubic-bezier(0.2, 0, 0, 1);
  --md-sys-motion-easing-emphasized-decelerate: cubic-bezier(0.05, 0.7, 0.1, 1);
  --md-sys-state-hover: 0.08;
  --md-sys-state-focus: 0.12;
  --md-sys-state-pressed: 0.12;
  --md-sys-state-dragged: 0.16;
  --md-sys-elevation-1: 0 1px 2px rgb(0 0 0 / 0.3), 0 1px 3px 1px rgb(0 0 0 / 0.15);
  --md-sys-elevation-2: 0 1px 2px rgb(0 0 0 / 0.3), 0 2px 6px 2px rgb(0 0 0 / 0.15);
}
@media (prefers-color-scheme: dark) {
  :root {
${block(true).replace(/^/gm, "  ")}
  }
}
`;
const out = join(process.cwd(), "src/theme/tokens.css");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`wrote ${out}`);
